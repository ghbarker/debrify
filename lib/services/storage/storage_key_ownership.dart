/// Ownership of every persisted key name declared on [StorageService]
/// (`const _…Key` / CloudSecretPrefs aliases) plus CloudSecretPrefs' own
/// credential keys and undeclared inline / interpolated prefs literals
/// the god file still reads. Each name is owned by exactly one store.
///
/// Façade rule: [StorageService] public static methods remain a forwarding
/// façade until callers move. `@Deprecated` on those forwards waits for Q2.
/// Encodings and key **strings** are frozen — later S2 slices reassign
/// [StorageKeyStore] ownership when a domain store is extracted; they must
/// not change the string.
enum StorageKeyStore {
  deviceMaintenancePrefs,
  ambientTrailerPrefs,
  /// Profile-scoped download destination strings (DownloadDestinationPrefs).
  downloadDestinationPrefs,
  /// Torrent search history and its recording preference.
  torrentSearchHistoryStore,
  /// Installation-wide remote device preferences (RemoteDevicePrefs).
  remoteDevicePrefs,
  /// Onboarding readiness compatibility flag (ProfileOnboardingState).
  profileOnboardingState,
  /// Movie/series Quick Play policy and legacy mirrors (QuickPlayPolicyPrefs).
  quickPlayPolicyPrefs,
  /// Local movie/series watchlist persistence (MyWatchlistStore).
  myWatchlistStore,
  /// Playback history and playlist persistence ([PlaybackProgressStore]).
  playbackProgressStore,

  /// Residual keys still declared or inlined on StorageService.
  ///
  /// [StorageService] `x` stays a forwarding façade for these until callers
  /// move. Do not `@Deprecated` the forwards until Q2.
  storageService,

  /// [CloudSecretPrefs] credential keys.
  cloudSecretPrefs,

  /// Home page defaults and remaining Home keys ([HomePrefs]).
  homePrefs,

  /// Stremio TV rotation, catalogs, filters, favorites ([StremioTvPrefs]).
  stremioTvPrefs,

  /// Reddit / Lemmy / YouTube ([SocialPrefs]).
  socialPrefs,

  /// Debrify TV display, filters, channels, favorites ([DebrifyTvPrefs]).
  debrifyTvPrefs,

  /// Provider-credential settings ([ProviderCredentialPrefs]).
  /// Integration toggles, hidden-from-nav, post-torrent / file-selection
  /// precedence, RD endpoint, PikPak session/folder prefs, WebDAV.
  /// Secret key *strings* stay on [cloudSecretPrefs].
  providerCredentialPrefs,

  /// In-app player A/V, external-player, skip-segment, UI-feedback,
  /// and network-tuning prefs ([PlayerPrefs]).
  playerPrefs,

  /// IPTV playlist, decoder, last-live, startup, series-audio, and
  /// continue-watching tracking ([IptvPrefs]).
  iptvPrefs,

  /// Sync style caches ([AppStylePrefs]): looks, docks, chrome, launch ident.
  appStylePrefs,

  /// Tracking source policy, catalog-sync switches, and Trakt / Simkl /
  /// MDBList credentials ([TrackingPrefs]). Owns `trackingSourceRevision`.
  /// [home_tick_sources] stays on [homePrefs].
  trackingPrefs,

  /// Default torrent filter JSON strings ([DefaultTorrentFilterPrefs]).
  defaultTorrentFilterPrefs,
}

